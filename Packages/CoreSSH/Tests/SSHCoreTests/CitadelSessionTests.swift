// MARK: - Test doubles

final class TestEvaluator: HostKeyEvaluator, @unchecked Sendable {
    private let lock = NSLock()
    private var recorded: [HostKeyCandidate] = []
    let decision: HostKeyDecision
    let delay: Duration

    init(decision: HostKeyDecision, delay: Duration = .zero) {
        self.decision = decision
        self.delay = delay
    }

    var candidates: [HostKeyCandidate] { lock.withLock { recorded } }

    func evaluate(_ candidate: HostKeyCandidate) async -> HostKeyDecision {
        lock.withLock { recorded.append(candidate) }
        if delay > .zero { try? await Task.sleep(for: delay) }
        return decision
    }
}

/// Consumes a session's event stream in the background and records everything.
final class EventRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var events: [SessionEvent] = []
    private var bytes: [UInt8] = []
    private var finished = false
    /// Set when output arrives before `.connected` or after `.closed`, or `.ready` is out of place.
    private var outputOutsideSession = false

    init(_ stream: AsyncStream<SessionEvent>) {
        Task {
            for await event in stream { self.record(event) }
            self.lock.withLock { self.finished = true }
        }
    }

    private func record(_ event: SessionEvent) {
        lock.withLock {
            if case .output(let chunk) = event {
                if !events.contains(.connected) || events.contains(where: { if case .closed = $0 { true } else { false } }) {
                    outputOutsideSession = true
                }
                bytes.append(contentsOf: chunk)
            } else {
                if event == .ready && (events.last != .connected || events.contains(.ready)) {
                    outputOutsideSession = true // .ready only once, straight after .connected
                }
                events.append(event)
            }
        }
    }

    /// Events other than output, in order (output is checked separately via `output`).
    var nonOutputEvents: [SessionEvent] {
        lock.withLock { events.filter { if case .output = $0 { false } else { true } } }
    }

    var output: [UInt8] { lock.withLock { bytes } }
    var outputText: String { String(decoding: output, as: UTF8.self) }
    var isFinished: Bool { lock.withLock { finished } }

    func waitForOutput(containing text: String, timeout: TimeInterval = 15,
                       file: StaticString = #filePath, line: UInt = #line) async throws {
        try await waitUntil(timeout: timeout, file: file, line: line,
                            message: { "output never contained \(text): \(self.outputText.suffix(2000))" }) {
            self.outputText.contains(text)
        }
    }

    func waitForOutput(timeout: TimeInterval, until predicate: @escaping @Sendable ([UInt8]) -> Bool) async throws {
        try await waitUntil(timeout: timeout, message: { "output condition not met (\(self.output.count) bytes)" }) {
            predicate(self.output)
        }
    }

    /// Waits until the non-output events are exactly `expected` (the recorder consumes on its own task, so
    /// it can lag slightly behind `start()` returning).
    func waitForEvents(_ expected: [SessionEvent], timeout: TimeInterval = 5,
                       file: StaticString = #filePath, line: UInt = #line) async throws {
        try await waitUntil(timeout: timeout, file: file, line: line,
                            message: { "events \(self.nonOutputEvents) never became \(expected)" }) {
            self.nonOutputEvents == expected
        }
    }

    func waitForFinish(timeout: TimeInterval = 20, file: StaticString = #filePath, line: UInt = #line) async throws {
        try await waitUntil(timeout: timeout, file: file, line: line,
                            message: { "event stream did not finish: \(self.nonOutputEvents)" }) { self.isFinished }
        XCTAssertFalse(lock.withLock { outputOutsideSession }, "output outside connected..closed, or .ready misplaced", file: file, line: line)
        let closedCount = nonOutputEvents.filter { if case .closed = $0 { true } else { false } }.count
        XCTAssertEqual(closedCount, 1, "exactly one .closed event", file: file, line: line)
        if case .closed = nonOutputEvents.last {} else { XCTFail("last event is not .closed", file: file, line: line) }
    }
}

final class TestFlag: @unchecked Sendable {
    private let lock = NSLock()
    private var flag = false
    var value: Bool { lock.withLock { flag } }
    func set() { lock.withLock { flag = true } }
}

struct WaitTimeout: Error, CustomStringConvertible {
    let description: String
}

func waitUntil(timeout: TimeInterval = 15, file: StaticString = #filePath, line: UInt = #line,
               message: @escaping @Sendable () -> String = { "condition not met" },
               _ condition: @escaping @Sendable () -> Bool) async throws {
    let deadline = Date().addingTimeInterval(timeout)
    while !condition() {
        if Date() > deadline {
            let text = message()
            XCTFail(text, file: file, line: line)
            throw WaitTimeout(description: text)
        }
        try await Task.sleep(for: .milliseconds(20))
    }
}

extension Array where Element == UInt8 {
    func lastRange(of needle: [UInt8]) -> Range<Int>? {
        guard needle.count <= count else { return nil }
        var i = count - needle.count
        while i >= 0 {
            if self[i..<(i + needle.count)].elementsEqual(needle) { return i..<(i + needle.count) }
            i -= 1
        }
        return nil
    }
}

extension ArraySlice where Element == UInt8 {
    func contains(subsequence needle: [UInt8]) -> Bool {
        guard needle.count <= count else { return false }
        var i = startIndex
        while i + needle.count <= endIndex {
            if self[i..<(i + needle.count)].elementsEqual(needle) { return true }
            i += 1
        }
        return false
    }
}
