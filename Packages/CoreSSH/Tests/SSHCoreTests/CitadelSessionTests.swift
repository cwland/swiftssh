import AppCore
import CoreModels
import Foundation
import XCTest
@testable import SSHCore

/// Integration tests for the Citadel engine against a real OpenSSH server (`TestSSHServer`).
final class CitadelSessionTests: XCTestCase {
    private var server: TestSSHServer!

    override func setUpWithError() throws {
        server = try TestSSHServer.start()
    }

    override func tearDown() {
        server?.stop()
        server = nil
    }

    // MARK: Tests

    func testPasswordLoginRunsShellAndEchoes() async throws {
        let evaluator = TestEvaluator(decision: .trusted)
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: evaluator)
        let recorder = EventRecorder(session.events)

        await session.start(cols: 80, rows: 24)
        XCTAssertEqual(recorder.nonOutputEvents, [.connected])

        await session.send(Array("echo hi-$((40+2))\n".utf8))
        try await recorder.waitForOutput(containing: "hi-42")

        let candidates = evaluator.candidates
        XCTAssertEqual(candidates.count, 1)
        XCTAssertEqual(candidates.first?.keyType, server.hostKeyType)
        XCTAssertEqual(candidates.first?.publicKeyBlob, server.hostKeyBlob)
        XCTAssertEqual(candidates.first?.hostPort, "[127.0.0.1]:\(server.port)")
        await session.close()
    }

    func testEd25519KeyLoginWithAndWithoutPassphrase() async throws {
        // Unencrypted key generated by the app's own generator.
        let generated = SSHKeyGenerator.ed25519(comment: "citadel-test")
        try server.authorize(publicKeyLine: generated.publicKey)
        try await assertShellWorks(.privateKey(type: .ed25519, pem: generated.privateKey, passphrase: nil))

        // Passphrase-protected key from ssh-keygen.
        let keyFile = server.directory.appendingPathComponent("client_ed25519")
        try TestSSHServer.run("/usr/bin/ssh-keygen", ["-q", "-t", "ed25519", "-N", "correct horse", "-f", keyFile.path])
        let pem = try String(contentsOf: keyFile, encoding: .utf8)
        try server.authorize(publicKeyLine: String(contentsOf: keyFile.appendingPathExtension("pub"), encoding: .utf8))
        try await assertShellWorks(.privateKey(type: .ed25519, pem: pem, passphrase: "correct horse"))

        // Wrong passphrase: authentication failure, nothing secret in the events.
        let session = CitadelSession(plan: plan(.privateKey(type: .ed25519, pem: pem, passphrase: "wrong horse")),
                                     hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.failed(.authenticationFailed))])
    }

    func testWrongPasswordFailsWithAuthenticationFailed() async throws {
        let wrong = "not-the-password-91b2"
        let session = CitadelSession(plan: plan(.password(wrong)), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.failed(.authenticationFailed))])
        let described = recorder.nonOutputEvents.map { "\($0)" }.joined()
            + (SessionError.authenticationFailed.errorDescription ?? "")
        XCTAssertFalse(described.contains(wrong))
    }

    func testRSAKeyIsReportedUnsupported() async throws {
        let evaluator = TestEvaluator(decision: .trusted)
        let pem = "-----BEGIN OPENSSH PRIVATE KEY-----\nAAAA\n-----END OPENSSH PRIVATE KEY-----\n"
        let session = CitadelSession(plan: plan(.privateKey(type: .rsa, pem: pem, passphrase: nil)), hostKeys: evaluator)
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.failed(.unsupportedKey("rsa")))])
        XCTAssertTrue(evaluator.candidates.isEmpty, "no connection is made for an unsupported key")
    }

    func testUnknownHostKeyRejectedStopsBeforeAuth() async throws {
        let evaluator = TestEvaluator(decision: .rejected)
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: evaluator)
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        try await recorder.waitForFinish()

        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.failed(.hostKeyRejected))])
        XCTAssertEqual(evaluator.candidates.map(\.publicKeyBlob), [server.hostKeyBlob])
        try await waitForLog(containing: "[preauth]")
        assertNoAuthenticationAttempt(in: server.log())
    }

    func testRemoteExitIsRemoteClosedNotError() async throws {
        for command in ["exit\n", "false; exit 3\n"] {
            let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: TestEvaluator(decision: .trusted))
            let recorder = EventRecorder(session.events)
            await session.start(cols: 80, rows: 24)
            await session.send(Array(command.utf8))
            try await recorder.waitForFinish()
            XCTAssertEqual(recorder.nonOutputEvents, [.connected, .closed(.remoteClosed)], "after \(command)")
        }
    }

    func testLargeOutputArrivesCompleteAndInOrder() async throws {
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        await session.send(Array("head -c 5000000 /dev/zero | tr '\\0' 'a'; echo END\n".utf8))

        let marker = Array(String(repeating: "a", count: 16).utf8) + Array("END".utf8)
        try await recorder.waitForOutput(timeout: 60) { bytes in
            bytes.count > 5_000_000 && bytes.suffix(1024).contains(subsequence: marker)
        }
        let bytes = recorder.output
        let endRange = try XCTUnwrap(bytes.lastRange(of: Array("END".utf8)))
        var runStart = endRange.lowerBound
        while runStart > 0 && bytes[runStart - 1] == UInt8(ascii: "a") { runStart -= 1 }
        XCTAssertEqual(endRange.lowerBound - runStart, 5_000_000, "exactly 5,000,000 'a' directly before END")
        await session.close()
    }

    func testResizeChangesRemoteSize() async throws {
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        await session.send(Array("stty size\n".utf8))
        try await recorder.waitForOutput(containing: "24 80")
        await session.resize(cols: 100, rows: 40)
        await session.send(Array("stty size\n".utf8))
        try await recorder.waitForOutput(containing: "40 100")
        await session.close()
    }

    func testRunCommandReturnsMergedOutput() async throws {
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)

        let probe = try await session.runCommand(OSDetector.probeCommand)
        XCTAssertTrue(probe.contains("Linux"), probe)

        let merged = try await session.runCommand("echo to-stdout; echo to-stderr >&2; exit 2")
        XCTAssertTrue(merged.contains("to-stdout"), merged)
        XCTAssertTrue(merged.contains("to-stderr"), merged)

        // The interactive shell is unaffected by the exec channels.
        await session.send(Array("echo still-$((1+1))\n".utf8))
        try await recorder.waitForOutput(containing: "still-2")
        await session.close()
    }

    func testCloseByUserEndsWithUserClosed() async throws {
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        await session.close()
        try await recorder.waitForFinish()
        await session.close()
        await session.send(Array("echo after-close\n".utf8))
        XCTAssertEqual(recorder.nonOutputEvents, [.connected, .closed(.userClosed)])
    }

    func testCloseBeforeStartEmitsUserClosedAndStartDoesNothing() async throws {
        let evaluator = TestEvaluator(decision: .trusted)
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: evaluator)
        let recorder = EventRecorder(session.events)
        await session.close()
        await session.start(cols: 80, rows: 24)
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.userClosed)])
        XCTAssertTrue(evaluator.candidates.isEmpty)
    }

    func testCloseDuringHostKeyPromptSendsNoCredentials() async throws {
        let evaluator = TestEvaluator(decision: .trusted, delay: .seconds(2))
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: evaluator)
        let recorder = EventRecorder(session.events)
        let started = Task { await session.start(cols: 80, rows: 24) }
        try await waitUntil { !evaluator.candidates.isEmpty }
        let clock = ContinuousClock()
        let closeStart = clock.now
        await session.close()
        await started.value
        XCTAssertLessThan(clock.now - closeStart, .seconds(1), "start returns promptly after close")
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.userClosed)])

        // The evaluator later says "trusted"; the abandoned attempt must still not authenticate.
        try await Task.sleep(for: .seconds(3))
        assertNoAuthenticationAttempt(in: server.log())
    }

    func testConnectTimeoutReportsTimedOut() async throws {
        let silent = try ListeningSocket()
        var plan = plan(.password(server.password))
        plan.port = silent.port
        let session = CitadelSession(plan: plan, hostKeys: TestEvaluator(decision: .trusted), connectTimeout: .seconds(1))
        let recorder = EventRecorder(session.events)
        let clock = ContinuousClock()
        let begin = clock.now
        await session.start(cols: 80, rows: 24)
        XCTAssertLessThan(clock.now - begin, .seconds(5))
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.closed(.failed(.timedOut))])
        withExtendedLifetime(silent) {}
    }

    /// The time the user spends answering the host key prompt does not count against the timeout,
    /// and a prompt longer than Citadel's fixed 10 s login timer still ends in a working session
    /// without asking twice.
    func testSlowHostKeyDecisionStillConnects() async throws {
        let evaluator = TestEvaluator(decision: .trusted, delay: .milliseconds(10_500))
        let session = CitadelSession(plan: plan(.password(server.password)), hostKeys: evaluator,
                                     connectTimeout: .seconds(3))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        XCTAssertEqual(recorder.nonOutputEvents, [.connected])
        XCTAssertEqual(evaluator.candidates.count, 1, "the user is asked once")
        await session.send(Array("echo slow-$((2+3))\n".utf8))
        try await recorder.waitForOutput(containing: "slow-5")
        await session.close()
        let log = server.log()
        XCTAssertEqual(log.components(separatedBy: "Accepted password").count - 1, 1, "credentials sent once:\n\(log)")
    }

    // MARK: Helpers

    private func plan(_ credential: SSHCredential) -> ConnectionPlan {
        ConnectionPlan(hostID: nil, label: "test", host: server.host, port: server.port,
                       username: server.username, credential: credential, engine: .citadel, startupScript: nil)
    }

    private func assertShellWorks(_ credential: SSHCredential, file: StaticString = #filePath, line: UInt = #line) async throws {
        let session = CitadelSession(plan: plan(credential), hostKeys: TestEvaluator(decision: .trusted))
        let recorder = EventRecorder(session.events)
        await session.start(cols: 80, rows: 24)
        XCTAssertEqual(recorder.nonOutputEvents, [.connected], file: file, line: line)
        await session.send(Array("echo key-$((6*7))\n".utf8))
        try await recorder.waitForOutput(containing: "key-42")
        await session.close()
        try await recorder.waitForFinish()
        XCTAssertEqual(recorder.nonOutputEvents, [.connected, .closed(.userClosed)], file: file, line: line)
    }

    private func waitForLog(containing text: String) async throws {
        let server: TestSSHServer = server
        try await waitUntil(timeout: 5) { server.log().contains(text) }
    }

    private func assertNoAuthenticationAttempt(in log: String, file: StaticString = #filePath, line: UInt = #line) {
        for marker in ["Accepted ", "Failed ", "Invalid user", "Postponed", "authentication failure"] {
            XCTAssertFalse(log.contains(marker), "sshd log shows an authentication attempt (\(marker)):\n\(log)",
                           file: file, line: line)
        }
    }
}

// MARK: - Test doubles

final class TestEvaluator: HostKeyEvaluator, @unchecked Sendable {
    private let lock = NSLock()
    private var recorded: [HostKeyCandidate] = []
    let decision: HostKeyDecision
    let delay: Duration

    init(decision: HostKeyDecision, delay: Duration = .zero) {
        self.decision = decision
        self.delay = delay
    }

    var candidates: [HostKeyCandidate] { lock.withLock { recorded } }

    func evaluate(_ candidate: HostKeyCandidate) async -> HostKeyDecision {
        lock.withLock { recorded.append(candidate) }
        if delay > .zero { try? await Task.sleep(for: delay) }
        return decision
    }
}

/// Consumes a session's event stream in the background and records everything.
final class EventRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var events: [SessionEvent] = []
    private var bytes: [UInt8] = []
    private var finished = false
    /// Set when output arrives before `.connected` or after `.closed`.
    private var outputOutsideSession = false

    init(_ stream: AsyncStream<SessionEvent>) {
        Task {
            for await event in stream { self.record(event) }
            self.lock.withLock { self.finished = true }
        }
    }

    private func record(_ event: SessionEvent) {
        lock.withLock {
            if case .output(let chunk) = event {
                if events.last != .connected { outputOutsideSession = true }
                bytes.append(contentsOf: chunk)
            } else {
                events.append(event)
            }
        }
    }

    /// Events other than output, in order (output is checked separately via `output`).
    var nonOutputEvents: [SessionEvent] {
        lock.withLock { events.filter { if case .output = $0 { false } else { true } } }
    }

    var output: [UInt8] { lock.withLock { bytes } }
    var outputText: String { String(decoding: output, as: UTF8.self) }
    var isFinished: Bool { lock.withLock { finished } }

    func waitForOutput(containing text: String, timeout: TimeInterval = 15,
                       file: StaticString = #filePath, line: UInt = #line) async throws {
        try await waitUntil(timeout: timeout, file: file, line: line,
                            message: { "output never contained \(text): \(self.outputText.suffix(2000))" }) {
            self.outputText.contains(text)
        }
    }

    func waitForOutput(timeout: TimeInterval, until predicate: @escaping @Sendable ([UInt8]) -> Bool) async throws {
        try await waitUntil(timeout: timeout, message: { "output condition not met (\(self.output.count) bytes)" }) {
            predicate(self.output)
        }
    }

    func waitForFinish(timeout: TimeInterval = 20, file: StaticString = #filePath, line: UInt = #line) async throws {
        try await waitUntil(timeout: timeout, file: file, line: line,
                            message: { "event stream did not finish: \(self.nonOutputEvents)" }) { self.isFinished }
        XCTAssertFalse(lock.withLock { outputOutsideSession }, "output outside connected..closed", file: file, line: line)
        let closedCount = nonOutputEvents.filter { if case .closed = $0 { true } else { false } }.count
        XCTAssertEqual(closedCount, 1, "exactly one .closed event", file: file, line: line)
        if case .closed = nonOutputEvents.last {} else { XCTFail("last event is not .closed", file: file, line: line) }
    }
}

struct WaitTimeout: Error, CustomStringConvertible {
    let description: String
}

func waitUntil(timeout: TimeInterval = 15, file: StaticString = #filePath, line: UInt = #line,
               message: @escaping @Sendable () -> String = { "condition not met" },
               _ condition: @escaping @Sendable () -> Bool) async throws {
    let deadline = Date().addingTimeInterval(timeout)
    while !condition() {
        if Date() > deadline {
            let text = message()
            XCTFail(text, file: file, line: line)
            throw WaitTimeout(description: text)
        }
        try await Task.sleep(for: .milliseconds(20))
    }
}

extension Array where Element == UInt8 {
    func lastRange(of needle: [UInt8]) -> Range<Int>? {
        guard needle.count <= count else { return nil }
        var i = count - needle.count
        while i >= 0 {
            if self[i..<(i + needle.count)].elementsEqual(needle) { return i..<(i + needle.count) }
            i -= 1
        }
        return nil
    }
}

extension ArraySlice where Element == UInt8 {
    func contains(subsequence needle: [UInt8]) -> Bool {
        guard needle.count <= count else { return false }
        var i = startIndex
        while i + needle.count <= endIndex {
            if self[i..<(i + needle.count)].elementsEqual(needle) { return true }
            i += 1
        }
        return false
    }
}
